#!/usr/bin/env python3
"""Copy the user-facing docs into the container image as bundled knowledge.

The general agent answers questions about HA-AgentHub itself from these
copies (``container/app/knowledge/``). The Docker build context is
``./container``, so the repo-level docs are not otherwise available at
runtime.

Usage:
    python scripts/sync_self_docs.py           # write/refresh the copies
    python scripts/sync_self_docs.py --check   # exit 1 when a copy is missing or stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
KNOWLEDGE_DIR = Path("container/app/knowledge")

# Repo-relative source docs bundled into the image (single source of truth).
SOURCE_DOCS: tuple[str, ...] = (
    "docs/user-guide.md",
    "docs/configuration.md",
    "docs/troubleshooting.md",
    "README.md",
)

MARKER_TEMPLATE = (
    "<!-- GENERATED by scripts/sync_self_docs.py from {source} - do not edit -->\n"
)


def _normalize(text: str) -> str:
    """Normalize line endings to LF."""
    return text.replace("\r\n", "\n").replace("\r", "\n")


def render_copy(source_rel: str, source_text: str) -> str:
    """Return the expected content of the bundled copy for one source doc."""
    return MARKER_TEMPLATE.format(source=source_rel) + _normalize(source_text)


def _read_text(path: Path) -> str:
    return _normalize(path.read_bytes().decode("utf-8"))


def find_stale(
    root: Path = REPO_ROOT, sources: tuple[str, ...] = SOURCE_DOCS
) -> list[str]:
    """Return a description of every bundled copy that is missing or out of date."""
    problems: list[str] = []
    target_dir = root / KNOWLEDGE_DIR
    for source_rel in sources:
        source = root / source_rel
        target = target_dir / Path(source_rel).name
        if not source.is_file():
            problems.append(f"{source_rel}: source file missing")
            continue
        if not target.is_file():
            problems.append(
                f"{target.relative_to(root).as_posix()}: missing (source {source_rel})"
            )
            continue
        if _read_text(target) != render_copy(source_rel, _read_text(source)):
            problems.append(
                f"{target.relative_to(root).as_posix()}: stale (source {source_rel})"
            )
    return problems


def sync(root: Path = REPO_ROOT, sources: tuple[str, ...] = SOURCE_DOCS) -> list[str]:
    """Write every bundled copy; return the repo-relative paths that changed."""
    target_dir = root / KNOWLEDGE_DIR
    target_dir.mkdir(parents=True, exist_ok=True)
    changed: list[str] = []
    for source_rel in sources:
        source = root / source_rel
        target = target_dir / Path(source_rel).name
        expected = render_copy(source_rel, _read_text(source))
        if target.is_file() and _read_text(target) == expected:
            continue
        target.write_bytes(expected.encode("utf-8"))
        changed.append(target.relative_to(root).as_posix())
    return changed


def main(argv: list[str] | None = None, root: Path = REPO_ROOT) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--check", action="store_true", help="verify the copies instead of writing them"
    )
    args = parser.parse_args(argv)

    if args.check:
        problems = find_stale(root)
        if problems:
            print(
                "Bundled self-docs are out of date (run: python scripts/sync_self_docs.py):"
            )
            for problem in problems:
                print(f"  - {problem}")
            return 1
        print(f"Bundled self-docs are up to date ({len(SOURCE_DOCS)} files).")
        return 0

    changed = sync(root)
    if changed:
        for path in changed:
            print(f"updated {path}")
    else:
        print("Bundled self-docs already up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
