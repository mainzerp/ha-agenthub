class _Agent(BaseAgent):
    @property
    def agent_card(self):
        return AgentCard(agent_id="general-agent", name="General", description="", timeout_sec=20.0)

    async def handle_task(self, task):
        return TaskResult(speech="")


def _local_tool(name: str = "local_echo", result: str = "local result") -> LocalTool:
    async def handler(arguments):
        return result

    return LocalTool(name=name, description="echo", parameters={"type": "object", "properties": {}}, handler=handler)


class TestLocalToolExecution:
    async def test_local_and_mcp_dispatch_with_spans(self):
        from app.analytics.tracer import SpanCollector

        collector = SpanCollector("trace-local-tool")
        manager = MagicMock()
        manager.call_tool = AsyncMock(return_value="mcp result")
        local = _local_tool()
        executor = _build_tool_executor(
            _Agent(),
            [{"name": "web_search", "_server_name": "ddg"}],
            manager,
            span_collector=collector,
            include_tool_payload_metadata=True,
            local_tools={local.name: local},
        )
        assert await executor("local_echo", {"q": 1}) == "local result"
        assert await executor("web_search", {"q": "x"}) == "mcp result"
        manager.call_tool.assert_awaited_once_with("ddg", "web_search", {"q": "x"})

        spans = [s for s in collector._spans if s["span_name"] == "mcp_tool_call"]
        assert len(spans) == 2
        local_span = next(s for s in spans if s["metadata"]["tool_name"] == "local_echo")
        mcp_span = next(s for s in spans if s["metadata"]["tool_name"] == "web_search")
        assert local_span["metadata"]["local"] is True
        assert local_span["metadata"]["server_name"] == "local"
        assert local_span["metadata"]["result_chars"] == len("local result")
        assert mcp_span["metadata"]["local"] is False
        assert mcp_span["metadata"]["server_name"] == "ddg"

    async def test_local_result_truncated_and_errors_reported(self):
        big = _local_tool("big", "x" * (MCP_TOOL_RESULT_MAX_CHARS * 2))

        async def failing(arguments):
            raise RuntimeError("kaputt")

        bad = LocalTool(name="bad", description="", parameters={}, handler=failing)
        executor = _build_tool_executor(
            _Agent(),
            [],
            None,
            span_collector=None,
            include_tool_payload_metadata=False,
            local_tools={"big": big, "bad": bad},
        )
        result = await executor("big", {})
        assert len(result) == MCP_TOOL_RESULT_MAX_CHARS
        assert result.endswith("[tool result truncated]")
        assert await executor("bad", {}) == "Tool error: kaputt"

    def test_collision_drops_mcp_tool_and_warns_once(self, caplog):
        local = _local_tool(SELF_INFO_TOOL_NAME)
        mcp_tools = [
            {"name": SELF_INFO_TOOL_NAME, "_server_name": "rogue"},
            {"name": "web_search", "_server_name": "ddg"},
        ]
        self_info_key = ("collision-agent", SELF_INFO_TOOL_NAME)
        from app.agents import tool_calling

        tool_calling._warned_tool_collisions.discard(self_info_key)
        with caplog.at_level("WARNING", logger="app.agents.tool_calling"):
            kept, local_map = merge_local_tools("collision-agent", mcp_tools, [local])
            merge_local_tools("collision-agent", mcp_tools, [local])
        assert [tool["name"] for tool in kept] == ["web_search"]
        assert set(local_map) == {SELF_INFO_TOOL_NAME}
        warnings = [r for r in caplog.records if "collides" in r.getMessage()]
        assert len(warnings) == 1

    async def test_collision_routes_to_local_handler(self):
        captured = {}

        async def fake_cwt(agent_id, messages, *, tools, tool_executor, **kwargs):
            captured["names"] = [t["function"]["name"] for t in tools]
            captured["result"] = await tool_executor("dup", {})
            return "ok"

        manager = MagicMock()
        manager.call_tool = AsyncMock(return_value="from mcp")
        with (
            patch("app.llm.client.complete_with_tools", new=fake_cwt),
            patch("app.db.repository.SettingsRepository.get_value", new=AsyncMock(return_value="")),
        ):
            await call_llm_with_mcp_tools(
                _Agent(),
                [{"role": "user", "content": "q"}],
                [{"name": "dup", "_server_name": "srv"}, {"name": "web_search", "_server_name": "srv"}],
                manager,
                local_tools=[_local_tool("dup", "from local")],
            )
        assert captured["names"] == ["dup", "web_search"]
        assert captured["result"] == "from local"
        manager.call_tool.assert_not_awaited()


