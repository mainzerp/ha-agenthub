class TestParsing:
    def test_sections_carry_heading_path_and_skip_noise(self):
        sections = parse_markdown_sections("guide.md", _SAMPLE_DOC)
        labels = [s.label for s in sections]
        assert labels == [
            "guide.md > Sample Guide",
            "guide.md > Sample Guide > Configure > MCP Servers",
            "guide.md > Sample Guide > Configure > Plugins",
            "guide.md > Sample Guide > Troubleshooting",
        ]
        mcp = sections[1]
        assert "GENERATED" not in sections[0].body
        assert "images/mcp.png" not in mcp.body
        # Headings inside fenced code stay content.
        assert "# Not a heading inside a fence" in mcp.body

    def test_real_bundled_docs_parse(self):
        sections = self_info.load_sections()
        sources = {s.source for s in sections}
        assert {"user-guide.md", "configuration.md", "troubleshooting.md", "README.md"} <= sources
        assert not any("Screenshot Index" in s.label for s in sections)


class TestSearch:
    def test_ranking_prefers_heading_match_and_handles_stems(self):
        sections = parse_markdown_sections("guide.md", _SAMPLE_DOC)
        ranked = rank_sections(sections, "adding mcp servers")
        assert ranked[0][1].heading_path[-1] == "MCP Servers"
        ranked = rank_sections(sections, "plugin")
        assert ranked[0][1].heading_path[-1] == "Plugins"

    def test_prefix_match(self):
        sections = parse_markdown_sections("guide.md", _SAMPLE_DOC)
        ranked = rank_sections(sections, "registration")
        assert ranked and ranked[0][1].heading_path[-1] == "MCP Servers"

    async def test_search_labels_hits(self, knowledge_dir):
        result = await search_docs("mcp server", knowledge_dir=knowledge_dir)
        assert "[guide.md > Sample Guide > Configure > MCP Servers]" in result
        assert "Add Server" in result

    async def test_no_hit_message(self, knowledge_dir):
        result = await search_docs("xyzzy quux", knowledge_dir=knowledge_dir)
        assert result.startswith("No matching section in the HA-AgentHub documentation")

    async def test_empty_query(self, knowledge_dir):
        assert (await search_docs("  ", knowledge_dir=knowledge_dir)).startswith("No query given")

    async def test_missing_knowledge_dir(self, tmp_path):
        missing = tmp_path / "absent"
        try:
            result = await search_docs("mcp", knowledge_dir=missing)
        finally:
            self_info._sections_cache.pop(missing, None)
        assert "not available" in result

    async def test_budget_is_respected_on_real_docs(self):
        result = await search_docs("configure settings agent cache voice", limit=8)
        assert len(result) <= self_info.DOCS_RESULT_BUDGET_CHARS
        assert len(result) < MCP_TOOL_RESULT_MAX_CHARS

    def test_format_truncates_to_budget(self):
        big = parse_markdown_sections("big.md", "# Big\n\n" + "word " * 5000)
        text = format_doc_hits(big, "word", budget=1000)
        assert len(text) <= 1000
        assert text.endswith("...")


