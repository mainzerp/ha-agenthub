def _load_sync_script():
    path = _REPO_ROOT / "scripts" / "sync_self_docs.py"
    spec = importlib.util.spec_from_file_location("sync_self_docs_under_test", path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


class TestSyncScript:
    def _fake_repo(self, tmp_path, module):
        for source in module.SOURCE_DOCS:
            target = tmp_path / source
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(f"# {source}\r\n\r\nBody text.\r\n".encode())
        return tmp_path

    def test_check_detects_missing_and_stale_copies(self, tmp_path, capsys):
        module = _load_sync_script()
        root = self._fake_repo(tmp_path, module)

        assert module.main(["--check"], root=root) == 1
        assert "missing" in capsys.readouterr().out

        assert module.main([], root=root) == 0
        assert module.main(["--check"], root=root) == 0
        copy = root / module.KNOWLEDGE_DIR / "user-guide.md"
        text = copy.read_bytes().decode()
        assert text.startswith("<!-- GENERATED by scripts/sync_self_docs.py from docs/user-guide.md")
        assert "\r" not in text

        (root / "docs" / "user-guide.md").write_text("# Changed\n", encoding="utf-8")
        capsys.readouterr()
        assert module.main(["--check"], root=root) == 1
        out = capsys.readouterr().out
        assert "user-guide.md: stale" in out
        assert "README.md" not in out

    def test_repo_copies_are_current(self):
        module = _load_sync_script()
        assert module.find_stale() == []
